-- LoDCORE Madrid • 02-tablas_procesadas.sql
-- Dataset integrado municipal (Fase F2/F3) con 92 columnas del panel validado,
-- (88 originales + 4 reales de la Etapa 1: Catastro, INE EVR, INE padrón 6y)
-- trazabilidad obligatoria y columnas virtuales para vistas APEX y scoring ONNX
-- =============================================================================

CREATE TABLE municipios_procesados (
    id_municipio NUMBER PRIMARY KEY,
    codigo_ine NUMBER(5) UNIQUE NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    comarca VARCHAR2(100) NOT NULL,
    tipologia VARCHAR2(50) NOT NULL,
    poblacion_actual NUMBER NOT NULL,
    anio_padron NUMBER NOT NULL,
    superficie_km2 NUMBER NOT NULL,
    latitud NUMBER NOT NULL,
    longitud NUMBER NOT NULL,
    tiempo_medio_madrid_minutos NUMBER NOT NULL,
    precio_m2_compra NUMBER NOT NULL,
    precio_m2_alquiler NUMBER,
    hospital_referencia VARCHAR2(255),
    camas_hospitalarias_cercanas NUMBER,
    restriccion_ambiental VARCHAR2(10),
    num_centros_salud NUMBER NOT NULL,
    num_medicos_ap NUMBER NOT NULL,
    num_plazas_escolares NUMBER NOT NULL,
    num_alumnos_matriculados NUMBER NOT NULL,
    num_centros_educativos NUMBER NOT NULL,
    paradas_transporte_publico NUMBER NOT NULL,
    cobertura_fibra_pct NUMBER NOT NULL,
    num_viviendas_totales_est NUMBER NOT NULL,
    stock_vivienda_vacia_est NUMBER NOT NULL,
    suelo_urbano_disponible_m2 NUMBER NOT NULL,
    densidad NUMBER NOT NULL,
    medicos_x1000 NUMBER NOT NULL,
    hab_por_medico NUMBER NOT NULL,
    centros_salud_x10k NUMBER NOT NULL,
    ocupacion_escolar_pct NUMBER NOT NULL,
    tasa_holgura_escolar NUMBER NOT NULL,
    centros_edu_x1000_alumnos NUMBER NOT NULL,
    paradas_x1000 NUMBER NOT NULL,
    vacias_x1000 NUMBER NOT NULL,
    suelo_m2_x_hab NUMBER NOT NULL,
    tasa_vivienda_vacia_pct NUMBER NOT NULL,
    rentabilidad_bruta_alquiler_pct NUMBER,
    personas_absorb_sanidad NUMBER NOT NULL,
    personas_absorb_educacion NUMBER NOT NULL,
    personas_absorb_vivienda NUMBER NOT NULL,
    personas_absorbibles_sin_colapso NUMBER NOT NULL,
    personas_acogida_efectiva NUMBER NOT NULL,
    factor_limitante VARCHAR2(50) NOT NULL,
    medicos_adicionales_necesarios NUMBER NOT NULL,
    plazas_escolares_adicionales_nec NUMBER NOT NULL,
    coste_estimado_ampliacion_servicios NUMBER NOT NULL,
    holgura_relativa_pct NUMBER NOT NULL,
    score_sanidad NUMBER NOT NULL,
    score_educacion NUMBER NOT NULL,
    score_servicios NUMBER NOT NULL,
    score_conectividad NUMBER NOT NULL,
    score_vivienda NUMBER NOT NULL,
    score_holgura NUMBER NOT NULL,
    indice_capacidad_global NUMBER NOT NULL,
    nivel_idoneidad VARCHAR2(50) NOT NULL,
    ranking_ica NUMBER NOT NULL,

    -- Etapa 1 (v1.1.0-F2): fuentes reales Catastro / INE EVR / INE padrón 6y
    valor_catastral_residencial_eur_m2 NUMBER NOT NULL,
    anio_valor_catastral NUMBER NOT NULL,
    migracion_neta_externa NUMBER NOT NULL,
    crecimiento_pob_pct_2020_2025 NUMBER NOT NULL,

    fuente_datos VARCHAR2(255) NOT NULL,
    fecha_carga VARCHAR2(50) NOT NULL,
    fecha_referencia VARCHAR2(50) NOT NULL,
    fecha_calculo VARCHAR2(50) NOT NULL,
    version_modelo VARCHAR2(50) NOT NULL,
    precio_predicho_avm_m2 NUMBER NOT NULL,
    gap_mercado_pct NUMBER NOT NULL,
    diagnostico_mercado VARCHAR2(50) NOT NULL,
    cluster_id NUMBER NOT NULL,
    arquetipo_codigo VARCHAR2(100) NOT NULL,
    arquetipo_nombre VARCHAR2(100) NOT NULL,
    poblacion_2027 NUMBER NOT NULL,
    poblacion_2029 NUMBER NOT NULL,
    poblacion_2031 NUMBER NOT NULL,
    anio_estimado_saturacion NUMBER NOT NULL,
    alerta_planificacion VARCHAR2(50) NOT NULL,
    img_local VARCHAR2(255),
    altitud_m NUMBER NOT NULL,
    carretera_acceso VARCHAR2(255),
    zona_crtm VARCHAR2(50),
    transporte_detalle VARCHAR2(500),
    sanidad_detalle VARCHAR2(500),
    camas_hospital NUMBER,
    educacion_detalle VARCHAR2(500),
    vivienda_detalle VARCHAR2(500),
    patrimonio_entorno VARCHAR2(500),
    observaciones_acogida VARCHAR2(500),
    fecha_disponible DATE NOT NULL,
    origen VARCHAR2(100) NOT NULL,
    metodo VARCHAR2(100) NOT NULL,
    dataset_version VARCHAR2(50) NOT NULL,

    -- Columnas virtuales de compatibilidad con vistas APEX y scoring ONNX N2
    tiempo_madrid_min NUMBER GENERATED ALWAYS AS (tiempo_medio_madrid_minutos) VIRTUAL,
    plazas_escolares NUMBER GENERATED ALWAYS AS (num_plazas_escolares) VIRTUAL,
    alumnos_matriculados NUMBER GENERATED ALWAYS AS (num_alumnos_matriculados) VIRTUAL,
    precio_avm_m2 NUMBER GENERATED ALWAYS AS (precio_predicho_avm_m2) VIRTUAL,

    CONSTRAINT chk_municipios_origen CHECK (
        REGEXP_LIKE(
            origen,
            '^(OBSERVADO|IMPUTADO|ESTIMADO|PROYECTADO|SIMULADO)(\+(OBSERVADO|IMPUTADO|ESTIMADO|PROYECTADO|SIMULADO))*$'
        )
    )
);
